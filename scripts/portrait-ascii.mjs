// Regenerates designs/glyph/portrait-ascii.ts from public/images/rithvik.jpeg (run after the photo changes):
//   node scripts/portrait-ascii.mjs
// Darker = denser glyph (a positive print on a dark screen); the near-white backdrop becomes blank.
import sharp from "sharp";
import { writeFileSync } from "node:fs";

const COLS = 64, ROWS = 36; // monospace cells are ~0.56 wide, so 64x36 cells cover a square photo
const RAMP = " .,:;-~=+*cxoO#%@";
const { data } = await sharp("public/images/rithvik.jpeg").resize(COLS, ROWS, { fit: "fill" }).grayscale().raw().toBuffer({ resolveWithObject: true });
const rows = [];
for (let y = 0; y < ROWS; y++) {
  let s = "";
  for (let x = 0; x < COLS; x++) {
    const l = data[y * COLS + x] / 255;
    s += l > 0.9 ? " " : RAMP[Math.min(RAMP.length - 1, Math.round(Math.pow(1 - l, 1.5) * (RAMP.length - 1)))];
  }
  rows.push(s);
}
writeFileSync("designs/glyph/portrait-ascii.ts", `// Generated by scripts/portrait-ascii.mjs from public/images/rithvik.jpeg. Do not edit.\nexport const PORTRAIT_ASCII: string[] = ${JSON.stringify(rows, null, 1)};\n`);
console.log(rows.join("\n"));
