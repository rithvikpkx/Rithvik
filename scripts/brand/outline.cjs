// One-off: outlines the wordmark strings in Geist (the site's typeface, SIL OFL 1.1) into components/site/mark/wordmark.ts,
// so lockups and the OG image render identically everywhere with no font loading.
// Needs opentype.js + the Geist TTFs (fonts.google.com/specimen/Geist), neither a dependency of the app:
//   NODE_PATH=<dir with opentype.js> node scripts/brand/outline.cjs <Geist-400.ttf> <Geist-500.ttf> <GeistMono-400.ttf>
const fs = require("node:fs");
const opentype = require("opentype.js");
const [regular, medium, mono] = process.argv.slice(2).map((p) => opentype.parse(fs.readFileSync(p).buffer.slice(0)));

// font size 100, baseline at y=0; letterSpacing is in em
const STRINGS = {
  name: [medium, "Rithvik Praveen Kumar", -0.02],
  first: [medium, "Rithvik", -0.02],
  last: [medium, "Praveen Kumar", -0.02],
  tag: [regular, "CS + Math @ Purdue", -0.005],
  url: [mono, "rithvik.ai", 0],
};
const out = {};
for (const [k, [font, text, ls]] of Object.entries(STRINGS)) {
  const p = font.getPath(text, 0, 0, 100, { kerning: true, letterSpacing: ls });
  const b = p.getBoundingBox();
  out[k] = { d: p.toPathData(2), w: +b.x2.toFixed(2) };
}
const cap = +((medium.tables.os2.sCapHeight / medium.unitsPerEm) * 100).toFixed(2);
fs.writeFileSync(
  "components/site/mark/wordmark.ts",
  `// Generated by scripts/brand/outline.cjs: strings outlined in Geist (SIL OFL 1.1, Vercel). Units: font size 100, baseline y=0.\n` +
    `/** Outlined wordmark strings: path data plus the ink's right edge (w), all at font size 100. */\n` +
    `export const WORDS = ${JSON.stringify(out, null, 2)} as const;\n/** Cap height at font size 100 (Geist Medium). */\nexport const CAP = ${cap};\n`,
);
